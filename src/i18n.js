export function detectLang(search, stored, navLang) {
  const q = new URLSearchParams(search).get('lang');
  if (q === 'es' || q === 'en') return q;
  if (stored === 'es' || stored === 'en') return stored;
  return /^es|^ca|^gl|^eu/i.test(navLang || '') ? 'es' : (navLang ? 'en' : 'es');
}

export function numberFormat(lang) {
  const f = new Intl.NumberFormat(lang === 'en' ? 'en-GB' : 'es-ES', { maximumFractionDigits: 1 });
  return (v) => f.format(Math.round(v * 10) / 10);
}
